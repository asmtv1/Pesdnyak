def verdict_seed(indices: tuple[int, ...], score: int) -> int:
    seed = score
    for position, index in enumerate(indices, start=1):
        seed = seed * 37 + (index + 1) * (position * 11)
    return seed


def _real_pool(score: int, low_verdict: str) -> tuple[str, ...]:
    for minimum, pool in REAL_VERDICTS:
        if score >= minimum:
            return pool
    return (low_verdict,)


def _creative_pool(score: int, low_verdict: str) -> tuple[str, ...]:
    if score >= 58:
        return CREATIVE_STRONG
    if score >= 38:
        return CREATIVE_MID
    if score >= 20:
        return CREATIVE_RISKY
    return (low_verdict, *CREATIVE_LOW)


def _absurd_pool(score: int, low_verdict: str) -> tuple[str, ...]:
    if score >= 28:
        return ABSURD_HIGH
    if score >= 18:
        return ABSURD_MID
    return (low_verdict, *ABSURD_LOW)


def verdict_for(
    score: int,
    low_verdict: str,
    level_id: LevelId = LevelId.REAL,
    variant_seed: int = 0,
) -> str:
    if level_id is LevelId.CREATIVE:
        pool = _creative_pool(score, low_verdict)
    elif level_id is LevelId.ABSURD:
        pool = _absurd_pool(score, low_verdict)
    else:
        pool = _real_pool(score, low_verdict)
    return pool[variant_seed % len(pool)]
