def _pool(situation_id: str, level: LevelId) -> LevelPool:
    reasons = tuple(WeightedText(text, weight) for text, weight in REASONS[situation_id][level])
    return LevelPool(reasons=reasons)


def _build_situation(blueprint: Blueprint) -> Situation:
    openers = OPENERS[blueprint.id]
    finales = tuple(WeightedText(text, weight) for text, weight in FINALES[blueprint.id])
    return Situation(
        id=blueprint.id,
        title=blueprint.title,
        emoji=blueprint.emoji,
        low_verdict=blueprint.low_verdict,
        openers=openers,
        finales=finales,
        levels={
            LevelId.REAL: _pool(blueprint.id, LevelId.REAL),
            LevelId.CREATIVE: _pool(blueprint.id, LevelId.CREATIVE),
            LevelId.ABSURD: _pool(blueprint.id, LevelId.ABSURD),
        },
    )


SITUATIONS = tuple(_build_situation(blueprint) for blueprint in BLUEPRINTS)
SITUATIONS_BY_ID = {situation.id: situation for situation in SITUATIONS}


def validate_catalog() -> None:
    if len(SITUATIONS) != 8 or len(SITUATIONS_BY_ID) != 8:
        raise ValueError("Catalog must contain eight uniquely identified situations")
    all_fragments: list[str] = []
    for situation in SITUATIONS:
        if len(situation.openers) != 6 or len(set(situation.openers)) != 6:
            raise ValueError(f"{situation.id}: expected six unique openers")
        if len(situation.finales) != 6 or len({x.text for x in situation.finales}) != 6:
            raise ValueError(f"{situation.id}: expected six unique finales")
        all_fragments.extend(situation.openers)
        all_fragments.extend(item.text for item in situation.finales)
        for level in LevelId:
            pool = situation.levels[level]
            expected_reasons = 7 if level is LevelId.REAL else 12
            if (
                len(pool.reasons) != expected_reasons
                or len({x.text for x in pool.reasons}) != expected_reasons
            ):
                raise ValueError(
                    f"{situation.id}/{level}: expected {expected_reasons} unique reasons"
                )
            if any(
                not any(marker in reason.text.lower() for marker in DOG_MARKERS)
                for reason in pool.reasons
            ):
                raise ValueError(f"{situation.id}/{level}: every reason must mention a dog")
            all_fragments.extend(item.text for item in pool.reasons)
    if len(all_fragments) != 344 or len(set(all_fragments)) != 344:
        raise ValueError("Catalog must contain 344 globally unique fragments")


validate_catalog()
